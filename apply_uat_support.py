"""Run from ~/SA_APIs:
    python3 apply_uat_support.py --app-api https://<uat app api host> --adv-api https://<uat advisor api host> --web https://<uat advisor web host> [--json-api-key KEY]

Adds a 'uat' environment to the framework:
  1. EnvironmentLoader accepts -Denv=uat
  2. src/main/resources/config/uat.properties is created from your qa.properties with the UAT hosts
  3. The test-data workbook can be chosen with -Dportfolio.testdata.workbook=testdata/<file>.xlsx
  4. Rows without a User ID are allowed (user_id is left out of the planner request)
Safe to run again."""
import argparse, re, shutil, sys, os
ap = argparse.ArgumentParser()
ap.add_argument("--app-api", required=True, help="UAT host replacing https://qaappapi.valueresearch.in")
ap.add_argument("--adv-api", required=True, help="UAT host replacing https://qaadvappapi.valueresearch.in")
ap.add_argument("--web", required=True, help="UAT advisor web host replacing https://advisorqa.valueresearch.in (origin/referer)")
ap.add_argument("--json-api-key", default=None, help="UAT json-api-key header, if different from QA")
a = ap.parse_args()
strip = lambda u: u.rstrip("/")

def patch(path, old, new, marker):
    s = open(path).read()
    if marker in s:
        print(path.split("/")[-1], ": already done"); return
    if old not in s:
        sys.exit(f"{path}: anchor not found - send this file to Claude")
    shutil.copy(path, path + ".bak-uat")
    open(path, "w").write(s.replace(old, new, 1)); print(path.split("/")[-1], ": patched")

# 1) environment list
patch("src/main/java/com/org/apiautomation/config/EnvironmentLoader.java",
      'Set.of("dev", "qa", "stage", "prod")', 'Set.of("dev", "qa", "stage", "prod", "uat")', '"uat"')

# 2) uat.properties from qa.properties
qa = "src/main/resources/config/qa.properties"; uat = "src/main/resources/config/uat.properties"
s = open(qa).read()
s = s.replace("https://qaadvappapi.valueresearch.in", strip(a.adv_api))
s = s.replace("https://qaappapi.valueresearch.in", strip(a.app_api))
s = s.replace("https://advisorqa.valueresearch.in", strip(a.web))
if a.json_api_key:
    s = re.sub(r"json-api-key:[^|]*", "json-api-key:" + a.json_api_key, s)
s = "# UAT - generated by apply_uat_support.py from qa.properties\n" + s
open(uat, "w").write(s); print("uat.properties : written")

# 3) workbook chosen by system property
patch("src/test/java/com/org/apitests/portfolio/ExcelTestDataReader.java",
      'QA_EXECUTION_DATA_WORKBOOK_RESOURCE = "testdata/Portfolio Planner Test CasesQA .xlsx";',
      'QA_EXECUTION_DATA_WORKBOOK_RESOURCE = System.getProperty("portfolio.testdata.workbook", "testdata/Portfolio Planner Test CasesQA .xlsx");',
      'portfolio.testdata.workbook')

# 4) blank User ID -> no user_id in request
t = "src/test/java/com/org/apitests/portfolio/PortfolioPlannerExecutionDataDrivenTests.java"
patch(t, "                    .userId(Long.parseLong(row.userId()))",
      "                    .userId(row.userId() == null || row.userId().isBlank() ? 0L : Long.parseLong(row.userId()))",
      "row.userId().isBlank() ? 0L")
s = open(t).read()
anchor = "            failIfPortfolioDataMissing(portfolioHttpResponse);"
add = '''
            if (row.userId() == null || row.userId().isBlank()) {
                // Test account given without User ID (e.g. UAT sheet): leave user_id out of the request
                request.without("user_id");
                description = request.toJson();
            }'''
if "given without User ID" not in s:
    if anchor not in s: sys.exit(t + ": anchor not found - send this file to Claude")
    s = s.replace(anchor, anchor + add, 1); open(t, "w").write(s); print(t.split("/")[-1], ": user_id patch added")
print("\nDone. Copy the UAT workbook to src/test/resources/testdata/ and run:")
print('./mvnw clean test-compile')
print('./mvnw test -Denv=uat -Dportfolio.testdata.workbook="testdata/Portfolio Planner Test Cases UAT.xlsx" -Dtest=PortfolioPlannerExecutionDataDrivenTests')
